import pytest

from tdp_core.config import DEFAULT_SETTINGS, with_overrides
from tdp_core.parsing import skip_reason
from tdp_core.parsing.filters import VENDOR_DIRS


def test_plain_file_is_kept() -> None:
    assert skip_reason("src/pkg/mod.py", b'"""Module."""\nx = 1\n') is None


def test_too_large_is_strictly_over_the_limit() -> None:
    settings = with_overrides(DEFAULT_SETTINGS, max_file_bytes=10)
    assert skip_reason("a.py", b"x" * 10, settings) is None
    assert skip_reason("a.py", b"x" * 11, settings) == "too_large"


@pytest.mark.parametrize("vendor_dir", sorted(VENDOR_DIRS))
def test_vendored_directories(vendor_dir: str) -> None:
    assert skip_reason(f"src/{vendor_dir}/lib/mod.py", b"x = 1\n") == "vendored"


def test_vendored_needs_an_exact_component() -> None:
    for path in ("src/vendored/mod.py", "venvs/mod.py", "my_vendor/mod.py", "vendor.py"):
        assert skip_reason(path, b"x = 1\n") is None


@pytest.mark.parametrize(
    "header",
    [
        "# This file is autogenerated.",
        "# AUTO-GENERATED by protoc",
        "# Do Not Edit",
        "# Generated by the protocol buffer compiler.",
        '"""Auto-generated module."""',
    ],
)
def test_generated_header(header: str) -> None:
    assert skip_reason("pb/mod.py", f"{header}\nx = 1\n".encode()) == "generated"


def test_generated_marker_only_in_first_five_lines() -> None:
    fifth = "\n" * 4 + "# do not edit\n"
    sixth = "\n" * 5 + "# do not edit\n"
    assert skip_reason("a.py", fifth.encode()) == "generated"
    assert skip_reason("a.py", sixth.encode()) is None


def test_minified_counts_characters_not_bytes() -> None:
    assert skip_reason("a.py", b"x = '" + b"a" * 995 + b"'\n") == "minified"  # 1001 chars
    assert skip_reason("a.py", b"x = '" + b"a" * 994 + b"'\n") is None  # 1000 chars
    assert skip_reason("a.py", b"\n" * 10 + b"y" * 1001 + b"\n") == "minified"
    assert skip_reason("a.py", ("x = '" + "é" * 900 + "'\n").encode()) is None  # 906 chars, 1806 bytes
    assert skip_reason("a.py", b"z" * 1000 + b"\r\n") is None  # line ending is not content


def test_first_matching_reason_wins() -> None:
    settings = with_overrides(DEFAULT_SETTINGS, max_file_bytes=100)
    generated_and_long = b"# generated by tool\n" + b"x" * 2000
    assert skip_reason("vendor/a.py", generated_and_long, settings) == "too_large"
    assert skip_reason("vendor/a.py", generated_and_long) == "vendored"
    assert skip_reason("a.py", generated_and_long) == "generated"
