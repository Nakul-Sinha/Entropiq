def test_caches_and_jobs_give_identical_results(
    run: Run, sc: Scenario, bundle: Bundle, tmp_path: Path
) -> None:
    cache = RecordingCache()
    szz_dir = tmp_path / "szz"
    first = analyze(sc.repo, sc.merge, bundle, cache=cache, jobs=1, szz_cache_dir=szz_dir)
    assert cache.puts > 0
    assert list(szz_dir.glob("*/*.json"))
    puts, hits = cache.puts, cache.hits
    second = analyze(sc.repo, "main", bundle, cache=cache, jobs=0, szz_cache_dir=szz_dir)
    assert cache.puts == puts
    assert cache.hits > hits
    expected = _comparable(run.result)
    for result in (first, second):
        assert _comparable(result) == expected
        assert_frame_equal(result.features, run.result.features)


