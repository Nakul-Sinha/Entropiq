def test_hidden_coupling_edges() -> None:
    graph: nx.DiGraph[str] = nx.DiGraph()
    graph.add_edge("m.py", "n.py")
    edges = [
        ("b.py", "a.py", 5, 0.6),  # tie with the reverse direction: the source that sorts first wins
        ("a.py", "b.py", 5, 0.6),
        ("d.py", "c.py", 6, 0.9),  # the stronger direction wins over the weaker one
        ("c.py", "d.py", 6, 0.7),
        ("n.py", "m.py", 5, 1.0),  # an import edge in the other direction drops the pair
        ("z.py", "y.py", 5, 0.5),  # a single direction keeps its orientation
        ("s.py", "s.py", 5, 1.0),  # self pairs never become edges
    ]
    assert _hidden_coupling_edges(edges, graph) == [
        GraphEdge("a.py", "b.py", "hidden_coupling", 0.6),
        GraphEdge("d.py", "c.py", "hidden_coupling", 0.9),
        GraphEdge("z.py", "y.py", "hidden_coupling", 0.5),
    ]
    assert _hidden_coupling_edges(list(reversed(edges)), graph) == _hidden_coupling_edges(edges, graph)
    assert _hidden_coupling_edges([], graph) == []


def test_history_since() -> None:
    assert _history_since(SNAPSHOT_TIME, None) is None
    assert _history_since(SNAPSHOT_TIME, 0) == SNAPSHOT_TIME
    assert _history_since(SNAPSHOT_TIME, 1095) == datetime(2019, 9, 21, 12, tzinfo=UTC)
    # git misreads --since=@<ts> before 1973-03-03, so such cutoffs mine the whole history instead
    assert _history_since(datetime(1975, 1, 1, tzinfo=UTC), 1095) is None
    assert _history_since(datetime(1976, 3, 3, 9, 46, 40, tzinfo=UTC), 1096) == datetime(
        1973, 3, 3, 9, 46, 40, tzinfo=UTC
    )
    assert _history_since(datetime(1976, 3, 3, 9, 46, 39, tzinfo=UTC), 1096) is None
    assert _history_since(SNAPSHOT_TIME, 10**9) is None


