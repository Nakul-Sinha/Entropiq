class RecordingCache:
    """A dict-backed ``StaticCache`` that counts hits and puts."""

    def __init__(self) -> None:
        self.store: dict[str, FileSyntax] = {}
        self.hits = 0
        self.puts = 0

    def get(self, blob_sha: str) -> FileSyntax | None:
        syntax = self.store.get(blob_sha)
        if syntax is not None:
            self.hits += 1
        return syntax

    def put(self, blob_sha: str, syntax: FileSyntax) -> None:
        self.puts += 1
        self.store[blob_sha] = syntax


class ZeroSatd:
    """A SATD classifier that rejects every comment."""

    def predict_proba(self, texts: Sequence[str]) -> npt.NDArray[np.float64]:
        return np.zeros(len(texts), dtype=np.float64)


def _git_state(repo: Path, config: Path) -> tuple[str, str]:
    return _git(repo, config, "status", "--porcelain"), _git(repo, config, "for-each-ref")


def _comparable(result: AnalysisResult) -> dict[str, Any]:
    """``to_jsonable(result)`` without the fields that depend on the clock."""
    data: dict[str, Any] = to_jsonable(result)
    data.pop("analyzed_at")
    for key in ("timings_s", "mine_timings_s", "total_s"):
        data["stats"].pop(key)
    return data


