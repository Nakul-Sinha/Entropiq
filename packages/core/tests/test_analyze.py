def test_composition_matches_the_parts(run: Run, sc: Scenario, bundle: Bundle) -> None:
    result = run.result
    hist = mine_history(sc.repo, sc.merge, since=SNAPSHOT_TIME - timedelta(days=1095), max_commits=20_000)
    bugfix = classify_bugfix(hist.commits, hist.file_changes)
    szz = szz_table(sc.repo, hist, bugfix, max_fixes=300)
    built = build_features(
        sc.repo,
        hist,
        Snapshot("repo", 0, SNAPSHOT_TIME, sc.merge),
        bugfix=bugfix,
        szz=szz,
        satd_model=load_default_classifier(),
        cache=None,
        jobs=1,
    )
    expected = built.features.set_index("path")[list(FEATURE_INPUT_COLUMNS)]
    assert_frame_equal(result.features, expected)

    X = result.features
    scores = bundle.ranker.score(X)
    priorities = priority_from_scores(scores)
    risk, low, high = bundle.calibrator.predict(scores)
    explanations = Explainer(bundle).explain(X)
    by_path = _by_path(result)
    for i, path in enumerate(X.index):
        f = by_path[path]
        assert f.score == float(scores[i])
        assert f.priority == int(priorities[i])
        assert (f.risk, f.risk_low, f.risk_high) == (float(risk[i]), float(low[i]), float(high[i]))
        e = explanations[i]
        assert f.reasons == e.reasons
        assert f.mitigations == e.mitigations
        assert f.debt_types == e.debt_types
        assert f.shap_by_family == e.shap_by_family


