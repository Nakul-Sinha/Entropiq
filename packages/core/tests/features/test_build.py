class FailingCache:
    """A StaticCache whose get and put always raise, counting the calls."""

    def __init__(self) -> None:
        self.calls = 0

    def get(self, blob_sha: str) -> FileSyntax | None:
        self.calls += 1
        raise RuntimeError("database is down")

    def put(self, blob_sha: str, syntax: FileSyntax) -> None:
        self.calls += 1
        raise RuntimeError("database is down")


def test_failing_cache_is_dropped(sc: Scenario, caplog: pytest.LogCaptureFixture) -> None:
    failing = FailingCache()
    store: StaticCache = failing
    with caplog.at_level(logging.WARNING, logger="tdp_core.features.cache"):
        res = _build(sc, cache=store)
    assert_frame_equal(res.features, sc.built.features)
    assert res.syntax == sc.built.syntax
    warnings = [r.message for r in caplog.records if "static cache" in r.message]
    assert warnings and all("get failed" in m for m in warnings)
    # One failing get per parse batch (the snapshot and the older versions), then the cache is dropped.
    assert len(warnings) == failing.calls == 2


