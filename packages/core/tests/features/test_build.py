def test_cc_trend_matches_a_polyfit_oracle(sc: Scenario) -> None:
    trend = _values(sc.built, "cc_trend")
    for path, versions in VERSIONS.items():
        xs = [-k * CC_TREND_STEP_DAYS / DAYS_PER_YEAR for k in versions]
        ys = [cc_sum(parse_python(name, src.encode())) for name, src in versions.values()]
        expected = float(np.polyfit(xs, ys, 1)[0]) if len(xs) > 1 else 0.0
        assert trend[path] == pytest.approx(expected, rel=1e-5, abs=1e-5), path
    assert trend["pkg/core.py"] > 0
    assert trend["pkg/legacy.py"] < 0
    assert trend["pkg/models.py"] > 0  # one more branch since day 201, from 4 versions
    assert trend["pkg/fresh.py"] == 0 and trend["scripts/tool.py"] == 0
    assert trend["pkg/util.py"] > 0  # helpers.py gained a branch on day 100


