def _values(result: BuildResult, column: str) -> dict[str, float]:
    frame = result.features
    return dict(zip(frame["path"].tolist(), frame[column].tolist(), strict=True))


def _reach_lineage(sc: Scenario) -> tuple[frozenset[str], dict[str, frozenset[str]]]:
    reach = reachable_shas(sc.repo, sc.snapshot.sha)
    commits = sc.hist.commits.filter(
        pc.is_in(sc.hist.commits.column("sha"), value_set=pa.array(sorted(reach)))
    )
    until = max(commits.column("author_time").to_pylist())
    return reach, path_lineage(sc.hist.file_changes, commits, until)


def _assert_component(result: BuildResult, frame: pd.DataFrame) -> None:
    got = result.features.set_index("path")[list(frame.columns)]
    want = frame.astype(np.float32)
    want.index = want.index.astype(got.index.dtype)
    assert_frame_equal(got, want, check_names=False)


