@pytest.mark.network
def test_requests_cold_and_warm(tmp_path: Path) -> None:
    import time

    from tdp_core.features.satd_model import load_default_classifier
    from tdp_core.mining.mirror import ensure_mirror
    from tdp_core.paths import data_dir

    mirror = data_dir() / "mirrors" / "psf__requests.git"
    if not mirror.is_dir():
        mirror = ensure_mirror("https://github.com/psf/requests.git", tmp_path / "requests.git")
    hist = mine_history(mirror, REQUESTS_SHA)
    when = int(run_git(["show", "-s", "--format=%ct", REQUESTS_SHA], mirror).decode().strip())
