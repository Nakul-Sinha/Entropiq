"""Files to leave out of analysis: too large, vendored, generated, minified (IMPLEMENTATION_PLAN.md P1.2)."""

from __future__ import annotations

import re

from tdp_core.config import DEFAULT_SETTINGS, Settings

VENDOR_DIRS = frozenset(
    {"vendor", "vendors", "third_party", "node_modules", "site-packages", ".venv", "venv", "_vendor"}
)
GENERATED_HEADER_LINES = 5
MAX_LINE_CHARS = 1000

_GENERATED = re.compile(r"(?i)auto-?generated|do not edit|generated by")


def skip_reason(path: str, source: bytes, settings: Settings = DEFAULT_SETTINGS) -> str | None:
    """Why ``path`` should not be analysed, or None to analyse it.

    Checks in order, returning the first match:

    - ``"too_large"``: ``len(source)`` (bytes) is over ``settings.max_file_bytes``.
    - ``"vendored"``: a component of the repo-relative POSIX ``path`` is in ``VENDOR_DIRS``.
    - ``"generated"``: one of the first 5 lines matches ``auto-?generated|do not edit|generated by``
      (case insensitive).
    - ``"minified"``: some line is longer than 1000 characters (UTF-8 decoded, line ending excluded).
    """
    if len(source) > settings.max_file_bytes:
        return "too_large"
    if any(part in VENDOR_DIRS for part in path.split("/")):
        return "vendored"
    header = source.split(b"\n", GENERATED_HEADER_LINES)[:GENERATED_HEADER_LINES]
    if any(_GENERATED.search(_decode(line)) for line in header):
        return "generated"
    # A line over the limit in characters is over it in bytes too, so only long byte lines get decoded.
    for line in source.split(b"\n"):
        if len(line) > MAX_LINE_CHARS and len(_decode(line).rstrip("\r")) > MAX_LINE_CHARS:
            return "minified"
    return None


def _decode(line: bytes) -> str:
    return line.decode("utf-8", errors="replace")
